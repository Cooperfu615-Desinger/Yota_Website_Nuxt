// Run after npm run generate. Routes serve the actual SSG files inside an isolated
// browser test context, without opening a local server or changing user storage.
import assert from 'node:assert/strict'
import { readFile, stat, mkdtemp } from 'node:fs/promises'
import { resolve, extname, sep } from 'node:path'
import { tmpdir } from 'node:os'
import { chromium } from 'playwright'

const root = resolve('docs')
const base = '/Yota_Website_Nuxt/'
const origin = 'http://bindings-preview.test'
const screenshots = await mkdtemp(resolve(tmpdir(), 'yota-bindings-'))
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.woff2': 'font/woff2', '.avif': 'image/avif', '.ico': 'image/x-icon' }
const browser = await chromium.launch({ headless: true })
const errors = []
try {
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    const context = await browser.newContext({ viewport })
    await context.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (url.origin !== origin) { await route.abort(); return }
      try {
        const pathname = decodeURIComponent(url.pathname)
        let file = resolve(root, pathname.startsWith(base) ? pathname.slice(base.length) : pathname.slice(1))
        if (file !== root && !file.startsWith(root + sep)) throw new Error('Outside static root')
        if ((await stat(file)).isDirectory()) file = resolve(file, 'index.html')
        await route.fulfill({ status: 200, contentType: mime[extname(file)] || 'application/octet-stream', body: await readFile(file) })
      } catch { await route.fulfill({ status: 404, body: 'Not found' }) }
    })
    const page = await context.newPage()
    await page.clock.install()
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (/hydration/i.test(message.text())) errors.push(message.text()) })
    page.on('response', response => { if (response.status() >= 400 && /_nuxt/.test(response.url())) errors.push(`${response.status()} ${response.url()}`) })
    const click = name => page.getByRole('button', { name, exact: true }).click()
    const tab = name => page.getByRole('tab', { name, exact: true }).click()
    const card = kind => page.locator(`[data-binding-provider="${kind}"]`)
    const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('jh_userInfo')))
    async function noOverflow() {
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${viewport.width}: document fits`)
      for (const selector of ['.account-binding-panel', '.social-authorization-dialog']) {
        for (const element of await page.locator(selector).all()) {
          assert.ok(await element.evaluate(el => el.scrollWidth <= el.clientWidth + 1), `${viewport.width}: ${selector} fits`)
        }
      }
    }
    await page.goto(`${origin}${base}lobby/member/?tab=bindings`)
    await click('立即登入 / 註冊')
    await click('以訪客身份快速進入')
    await page.locator('[role="dialog"][aria-labelledby="auth-modal-title"]').waitFor({state:'hidden'})
    await page.waitForURL(/\/lobby\/member\/?\?tab=bindings$/)
    await tab('帳號綁定')
    await card('email').waitFor()
    assert.equal(await page.locator('[data-binding-provider]').count(), 5)
    const original = await stored()
    const wallets = await page.locator('.member-sidebar-wallet').innerText()
    await noOverflow()
    await page.screenshot({path:`${screenshots}/${viewport.width}-initial.png`,fullPage:true})
    await card('email').getByLabel('Email', {exact:true}).fill('bad')
    await card('email').getByRole('button',{name:'發送 Email 驗證碼',exact:true}).click()
    assert.ok((await card('email').getByRole('alert').innerText()).includes('有效'))
    await card('phone').getByLabel('手機號碼',{exact:true}).fill('123')
    await card('phone').getByRole('button',{name:'發送手機驗證碼',exact:true}).click()
    assert.ok((await card('phone').getByRole('alert').innerText()).includes('09'))
    await card('phone').getByLabel('手機號碼',{exact:true}).fill('0912345678')
    await card('phone').getByRole('button',{name:'發送手機驗證碼',exact:true}).click()
    await card('email').getByLabel('Email',{exact:true}).fill(' member@example.test ')
    await card('email').getByRole('button',{name:'發送 Email 驗證碼',exact:true}).click()
    const firstCode = await card('email').locator('.binding-demo-code strong').innerText()
    await card('email').getByLabel('驗證碼',{exact:true}).fill('123')
    assert.ok(await card('email').getByRole('button',{name:'確認 Email 綁定',exact:true}).isDisabled())
    await card('email').getByLabel('驗證碼',{exact:true}).fill(firstCode === '999999' ? '888888' : '999999')
    await card('email').getByRole('button',{name:'確認 Email 綁定',exact:true}).click()
    assert.ok((await card('email').getByRole('alert').innerText()).includes('錯誤'))
    assert.equal((await stored()).email,'','wrong code does not save a new address')
    await card('phone').getByRole('button',{name:'修改手機號碼',exact:true}).click()
    assert.ok(await card('phone').getByRole('button',{name:'發送手機驗證碼',exact:true}).isDisabled(),'return does not bypass cooldown')
    await noOverflow()
    await page.screenshot({path:`${screenshots}/${viewport.width}-otp.png`,fullPage:true})
    await page.clock.runFor(61000)
    await card('email').getByRole('button',{name:'重新發送驗證碼',exact:true}).click()
    const currentCode = await card('email').locator('.binding-demo-code strong').innerText()
    assert.equal(await card('email').getByLabel('驗證碼',{exact:true}).inputValue(),'','resend clears entered code')
    if (currentCode !== firstCode) {
      await card('email').getByLabel('驗證碼',{exact:true}).fill(firstCode)
      await card('email').getByRole('button',{name:'確認 Email 綁定',exact:true}).click()
      assert.ok((await card('email').getByRole('alert').innerText()).includes('錯誤'),'old email code is rejected')
    }
    await card('email').getByLabel('驗證碼',{exact:true}).fill(currentCode)
    await card('email').getByRole('button',{name:'確認 Email 綁定',exact:true}).click()
    assert.ok(await card('email').getByRole('button',{name:'確認 Email 綁定',exact:true}).isDisabled())
    await page.clock.runFor(700)
    await card('email').getByText('已綁定',{exact:true}).waitFor()
    await card('phone').getByRole('button',{name:'發送手機驗證碼',exact:true}).click()
    await card('phone').getByLabel('驗證碼',{exact:true}).fill('123456')
    await card('phone').getByRole('button',{name:'確認手機綁定',exact:true}).click()
    // Leaving during the delay must cancel completion.
    await tab('基本資料')
    await page.clock.runFor(700)
    assert.equal((await stored()).accountBindings.phone,false)
    const emailField = page.locator('#member-page-profile-email')
    assert.equal(await emailField.inputValue(),'member@example.test')
    assert.ok(await emailField.isDisabled())
    await page.locator('#member-page-profile-name').fill('驗證後暱稱')
    await click('儲存資料')
    await page.clock.runFor(550)
    assert.equal((await stored()).accountBindings.email,true,'basic profile save retains Email verification')
    await tab('帳號綁定')
    await card('phone').getByLabel('手機號碼',{exact:true}).fill('0912345678')
    await card('phone').getByRole('button',{name:'發送手機驗證碼',exact:true}).click()
    await card('phone').getByLabel('驗證碼',{exact:true}).fill('123456')
    await card('phone').getByRole('button',{name:'確認手機綁定',exact:true}).click()
    await page.clock.runFor(700)
    for (const [kind,label] of [['google','Google'],['apple','APPLE'],['facebook','FB']]) {
      await card(kind).getByRole('button',{name:`開始綁定 ${label}`,exact:true}).click()
      await page.clock.runFor(1600)
      const dialog = page.getByRole('dialog',{name:`綁定 ${label} 帳號`,exact:true})
      await dialog.waitFor()
      if (kind === 'facebook') await page.keyboard.press('Escape')
      else await dialog.getByRole('button',{name:'取消',exact:true}).click()
      await dialog.waitFor({state:'hidden'})
      assert.equal((await stored()).accountBindings[kind],false,'cancel does not bind')
      await card(kind).getByRole('button',{name:`開始綁定 ${label}`,exact:true}).click()
      await page.clock.runFor(1600)
      await noOverflow()
      if (kind === 'facebook') await page.screenshot({path:`${screenshots}/${viewport.width}-authorization.png`,fullPage:true})
      await dialog.getByRole('button',{name:'允許並綁定',exact:true}).click()
      await page.clock.runFor(1600)
      await dialog.waitFor({state:'hidden'})
      assert.equal((await stored()).accountBindings[kind],true)
    }
    const completed = await stored()
    for (const key of ['id','account','authProvider','vip','invitationCode']) assert.equal(completed[key],original[key],key)
    assert.equal(await page.locator('.member-sidebar-wallet').innerText(),wallets,'binding does not alter balances')
    assert.equal(completed.phone,'0912345678')
    assert.equal(completed.email,'member@example.test')
    assert.equal(await page.locator('[data-binding-provider] button').count(),0,'bound cards have no replacement action')
    await noOverflow()
    await page.screenshot({path:`${screenshots}/${viewport.width}-completed.png`,fullPage:true})
    await page.reload()
    await card('email').getByText('已綁定',{exact:true}).waitFor()
    assert.deepEqual((await stored()).accountBindings,completed.accountBindings,'refresh restores completed bindings')
    // Verify the layered profile dialog keeps open when authorization is cancelled.
    await page.evaluate(() => {
      const u=JSON.parse(localStorage.getItem('jh_userInfo')); u.accountBindings.facebook=false; localStorage.setItem('jh_userInfo',JSON.stringify(u))
    })
    await page.reload()
    await page.getByRole('button',{name:'開啟玩家資料',exact:true}).click()
    const profileDialog = page.locator('.member-profile-modal-overlay')
    await profileDialog.waitFor()
    await profileDialog.getByRole('tab',{name:'帳號綁定',exact:true}).click()
    await profileDialog.locator('[data-binding-provider="facebook"]').getByRole('button',{name:'開始綁定 FB',exact:true}).click()
    await page.clock.runFor(1600)
    await page.keyboard.press('Escape')
    await page.locator('.social-authorization-dialog').waitFor({state:'hidden'})
    assert.ok(await profileDialog.isVisible(),'Escape cancels only authorization layer')
    await page.keyboard.press('Escape')
    await profileDialog.waitFor({state:'hidden'})
    await context.close()
    console.log(`PASS account binding UI ${viewport.width}×${viewport.height}`)
  }
  // Legacy filled Email stays readonly/pending until the original address is verified.
  const context = await browser.newContext({viewport:{width:1440,height:1000}})
  await context.route('**/*',async route=>{
    const url=new URL(route.request().url()); if(url.origin!==origin)return route.abort()
    try {let file=resolve(root,decodeURIComponent(url.pathname).slice(base.length));if((await stat(file)).isDirectory())file=resolve(file,'index.html');await route.fulfill({status:200,contentType:mime[extname(file)]||'application/octet-stream',body:await readFile(file)})}catch{await route.fulfill({status:404,body:'Not found'})}
  })
  await context.addInitScript(() => {
    localStorage.setItem('jh_isLoggedIn','true')
    localStorage.setItem('jh_userInfo',JSON.stringify({id:'P100',account:'legacy888',authProvider:'account',email:'old@example.test',emailLocked:true,phone:'0912***888',accountBindings:{phone:true,google:true}}))
  })
  const page=await context.newPage()
  await page.clock.install()
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(/hydration/i.test(message.text()))errors.push(message.text())})
  await page.goto(`${origin}${base}lobby/member/?tab=bindings`)
  const email=page.locator('[data-binding-provider="email"]')
  await email.getByText('待驗證',{exact:true}).waitFor()
  assert.equal(await email.getByLabel('Email',{exact:true}).getAttribute('readonly'),'')
  assert.equal(await email.getByLabel('Email',{exact:true}).inputValue(),'old@example.test')
  await email.getByRole('button',{name:'發送 Email 驗證碼',exact:true}).click()
  const code=await email.locator('.binding-demo-code strong').innerText()
  await email.getByLabel('驗證碼',{exact:true}).fill(code)
  await email.getByRole('button',{name:'確認 Email 綁定',exact:true}).click()
  await page.clock.runFor(700)
  await email.getByText('已綁定',{exact:true}).waitFor()
  await context.close()
  // Existing social login entry points still create a demo identity, not a binding update.
  for (const [kind,label] of [['google','Google'],['apple','APPLE'],['facebook','FB'],['line','LINE']]) {
    const context=await browser.newContext({viewport:{width:1440,height:1000}})
    await context.route('**/*',async route=>{
      const url=new URL(route.request().url()); if(url.origin!==origin)return route.abort()
      try {let file=resolve(root,decodeURIComponent(url.pathname).slice(base.length));if(file!==root&&!file.startsWith(root+sep))throw new Error('Outside root');if((await stat(file)).isDirectory())file=resolve(file,'index.html');await route.fulfill({status:200,contentType:mime[extname(file)]||'application/octet-stream',body:await readFile(file)})}catch{await route.fulfill({status:404,body:'Not found'})}
    })
    const page=await context.newPage()
  await page.clock.install()
    page.on('pageerror',error=>errors.push(error.message))
    page.on('console',message=>{if(/hydration/i.test(message.text()))errors.push(message.text())})
    await page.goto(`${origin}${base}lobby/member/?tab=bindings`)
    await page.getByRole('button',{name:'立即登入 / 註冊',exact:true}).click()
    await page.locator(`button.social-${kind}`).click()
    await page.clock.runFor(1600)
    let dialog=page.getByRole('dialog',{name:`使用 ${label} 登入`,exact:true})
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    assert.ok(await page.locator(`button.social-${kind}`).evaluate(el=>el===document.activeElement),'cancel restores provider focus')
    await page.locator(`button.social-${kind}`).click()
    await page.clock.runFor(1600)
    await dialog.getByRole('button',{name:'允許並繼續',exact:true}).click()
    await page.clock.runFor(1600)
    await dialog.waitFor({state:'hidden'})
    await page.waitForURL(/\/lobby\/member\/?\?tab=bindings$/)
    await page.locator('[data-binding-provider="email"]').waitFor()
    const u=await page.evaluate(()=>JSON.parse(localStorage.getItem('jh_userInfo')))
    assert.equal(u.authProvider,kind)
    assert.equal(u.accountBindings.email,false,'social login does not verify Email')
    if(kind!=='line')assert.equal(u.accountBindings[kind],true,'login initializes its own social connection')
    await context.close()
  }
  assert.deepEqual(errors,[],'no page errors, hydration warnings or missing chunks')
  console.log(`Screenshots: ${screenshots}`)
} finally { await browser.close() }
