// Run after npm run generate; exercises hydration and UI on the actual SSG output.
import assert from 'node:assert/strict'
import { createServer } from 'node:http'
import { readFile, stat, mkdtemp } from 'node:fs/promises'
import { resolve, extname, sep } from 'node:path'
import { tmpdir } from 'node:os'
import { chromium } from 'playwright'

const root = resolve('docs')
const base = '/Yota_Website_Nuxt/'
const screenshots = await mkdtemp(resolve(tmpdir(), 'yota-messages-'))
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.woff2': 'font/woff2', '.avif': 'image/avif' }
const server = createServer(async (req, res) => {
  try {
    const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname)
    if (!pathname.startsWith(base)) { res.writeHead(404); res.end(); return }
    let file = resolve(root, pathname.slice(base.length))
    if (file !== root && !file.startsWith(root + sep)) { res.writeHead(403); res.end(); return }
    if ((await stat(file)).isDirectory()) file = resolve(file, 'index.html')
    res.setHeader('Content-Type', mime[extname(file)] || 'application/octet-stream')
    res.end(await readFile(file))
  } catch { res.writeHead(404); res.end() }
})
await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve) })
const url = process.env.MESSAGE_CENTER_URL || `http://127.0.0.1:${server.address().port}${base}`
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (/hydration/i.test(message.text())) errors.push(message.text()) })
  page.on('response', response => { if (response.status() >= 400 && /_nuxt/.test(response.url())) errors.push(`${response.status()} ${response.url()}`) })
  const click = name => page.getByRole('button', { name, exact: true }).click()
  const category = label => page.locator('.message-category-rail').getByRole('button', { name: new RegExp(`^${label}，`) }).click()
  const unread = async () => (await page.locator('.message-total').innerText()).match(/\d+/)[0]
  const inboxLink = () => page.locator('.lobby-sidebar').getByRole('link', { name: /^信箱(?:，|$)/ })
  const newsLink = () => page.locator('.lobby-sidebar').getByRole('link', { name: /^最新消息(?:，|$)/ })
  async function noOverflow() { assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'no document overflow') }
  async function login(account = 'mailTester') {
    await page.locator('#login-account').fill(account)
    await page.locator('#login-password').fill('prototype123')
    await click('登入')
    await page.locator('[role="dialog"][aria-labelledby="auth-modal-title"]').waitFor({ state: 'hidden' })
  }
  await page.goto(`${url}lobby/mailbox/`)
  assert.ok(await page.getByRole('heading', { name: '信箱', exact: true }).isVisible())
  await click('立即登入 / 註冊')
  await login()
  await page.locator('.message-center-shell').waitFor()
  assert.equal(await unread(), '3', 'desktop visible first mail is read')
  assert.ok(await page.getByRole('button', { name: '刪除信件', exact: true }).isDisabled())
  const before = await page.locator('.lobby-header').innerText()
  assert.ok(before.includes('10,000,000'))
  await page.screenshot({ path: `${screenshots}/desktop-inbox.png`, fullPage: true })
  await click('領取')
  assert.ok((await page.locator('.lobby-header').innerText()).includes('10,050,000'))
  assert.ok(await page.getByRole('button', { name: '已領取', exact: true }).isDisabled())
  assert.ok(await page.locator('.message-batch').isDisabled())
  await click('刪除信件')
  assert.equal(await page.locator('.message-entry').count(), 1)
  assert.ok(!(await page.locator('.message-list').innerText()).includes('維護補償已送達'))
  await category('活動推廣')
  assert.ok((await page.locator('.message-detail').innerText()).includes('活動資訊邀請'))
  assert.equal(await page.locator('.message-reward').count(), 0)
  await click('刪除信件')
  assert.equal(await page.locator('.message-entry').count(), 0)
  assert.ok(await page.getByText('目前沒有活動推廣', { exact: true }).isVisible())
  await category('補單通知')
  assert.ok((await page.locator('.message-detail').innerText()).includes('補單申請進度通知'))
  await page.locator('.lobby-sidebar').getByRole('link', { name: '紀錄', exact: true }).click()
  const newestRecord = page.locator('.record-card').first()
  assert.ok((await newestRecord.innerText()).includes('信箱附件領取'))
  assert.ok((await newestRecord.innerText()).includes('+50,000'))
  assert.ok((await newestRecord.innerText()).includes('金幣'))
  await newsLink().click()
  await category('遊戲公告')
  assert.equal(await page.locator('.message-detail-footer').count(), 0)
  assert.equal(await page.locator('.message-reward').count(), 0)
  await page.screenshot({ path: `${screenshots}/desktop-news.png`, fullPage: true })
  await category('維護公告')
  await category('系統公告')
  await category('活動')
  assert.equal(await page.locator('.event-list-item').count(), 12)
  await page.locator('.event-list-item').filter({ hasText: '活動參加流程示範' }).click()
  const newsUnreadBefore = await unread()
  await page.locator('.lobby-sidebar').getByRole('link', { name: '活動', exact: true }).click()
  const sharedEvent = page.locator('.event-list-item').filter({ hasText: '活動參加流程示範' })
  assert.equal(await sharedEvent.locator('.event-unread').count(), 0, 'activity reads are shared')
  await sharedEvent.click()
  await click('前往參加')
  await page.waitForURL(new RegExp(`${url}lobby/?$`))
  assert.ok(!(await page.locator('body').innerText()).includes('示範報名'))
  await newsLink().click()
  assert.equal(await unread(), newsUnreadBefore, 'news reads persist across routes')
  await page.locator('.event-list-item').filter({ hasText: '活動諮詢服務' }).click()
  await page.locator('.events-action').click()
  await page.waitForURL(/chat\?channel=support/)
  const draft = page.getByPlaceholder('請輸入問題內容…')
  assert.ok((await draft.inputValue()).includes('活動諮詢服務'))
  assert.ok((await page.locator('.support-thread-header').innerText()).includes('尚未送出'))
  await inboxLink().click()
  await category('系統通知')
  assert.equal(await page.locator('.message-entry').count(), 1, 'deleted mail stays deleted after navigation')
  await noOverflow()
  // Logout resets account-scoped mail and balances before the next account signs in.
  await click('登出')
  await click('確認登出')
  await page.waitForURL(url)
  await page.goto(`${url}lobby/mailbox/`)
  await click('立即登入 / 註冊')
  await login('mailSecond')
  await page.locator('.message-center-shell').waitFor()
  await page.locator('.message-entry').first().waitFor()
  assert.equal(await page.locator('.message-entry').count(), 2)
  assert.ok((await page.locator('.lobby-header').innerText()).includes('10,000,000'))
  await page.locator('.message-batch').click()
  assert.ok((await page.locator('.lobby-header').innerText()).includes('10,050,000'))
  assert.equal(await unread(), '3', 'batch does not read other categories')
  // Fresh mobile session must not read the selected-but-hidden first detail.
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } })
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.addInitScript(() => { localStorage.setItem('jh_isLoggedIn', 'true') })
  await mobile.goto(`${url}lobby/mailbox/`)
  await mobile.locator('.message-center-shell').waitFor()
  assert.equal(await mobile.locator('.message-total').innerText(), '未讀 4 則')
  assert.ok(!(await mobile.locator('.message-detail').isVisible()))
  await mobile.screenshot({ path: `${screenshots}/mobile-inbox-list.png`, fullPage: true })
  await mobile.locator('.message-entry-main').first().click()
  assert.equal(await mobile.locator('.message-total').innerText(), '未讀 3 則')
  assert.ok(await mobile.locator('.message-detail').isVisible())
  await mobile.screenshot({ path: `${screenshots}/mobile-inbox-detail.png`, fullPage: true })
  await mobile.getByRole('button', { name: '返回列表', exact: false }).click()
  assert.ok(await mobile.locator('.message-list').isVisible())
  for (const width of [360, 768, 1006, 1143, 1579]) {
    await mobile.setViewportSize({ width, height: 900 })
    await mobile.waitForFunction(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
  }
  await mobile.setViewportSize({ width: 390, height: 844 })
  await mobile.goto(`${url}lobby/inbox/`)
  await mobile.locator('.event-list-item').first().waitFor()
  assert.equal(await mobile.locator('.event-unread').count(), 12)
  await mobile.locator('.event-list-item').first().click()
  assert.equal(await mobile.locator('.event-unread').count(), 11)
  await mobile.screenshot({ path: `${screenshots}/mobile-news-event.png`, fullPage: true })
  assert.deepEqual(errors, [])
  console.log(`Message center browser checks passed. Screenshots: ${screenshots}`)
} finally {
  await browser.close()
  await new Promise(resolve => server.close(resolve))
}
